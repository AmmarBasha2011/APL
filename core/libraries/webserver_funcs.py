def _webs_replace(match):
    dot = match.group("dot")
    word = match.group("word")
    open_paren = match.group("open")
    if word in USER_NAMES:
        return match.group(0)
    if dot:
        if open_paren and word in WEBS_METHODS:
            return "." + WEBS_METHODS[word] + open_paren
        if word in WEBS_PROPS:
            return "." + WEBS_PROPS[word]
        return match.group(0)
    if word in WEBS_CONSTS:
        return WEBS_CONSTS[word]
    if word in WEBS_FUNCS:
        return WEBS_FUNCS[word] + (open_paren or "")
    return match.group(0)


