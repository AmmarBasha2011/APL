USER_NAMES = set()


def _storedeep_replace(match):
    dot = match.group("dot")
    word = match.group("word")
    open_paren = match.group("open")
    if word in USER_NAMES:
        return match.group(0)
    if dot:
        return match.group(0)
    if word in STOD_CONSTS:
        return STOD_CONSTS[word]
    if word in STOD_FUNCS:
        return STOD_FUNCS[word] + (open_paren or "")
    return match.group(0)


def STOD_SUBSTITUTE(text):
    """يترجم كلمات المكتبة في نص واحد ويُرجع المترجم."""
    if not text:
        return text
    return _STOD_TOKEN.sub(_storedeep_replace, text)
