# نحو 1100 كلمة: بناء تعبير نمطي واحد بدل `a|b|c|...` يوفّر بضع ملي ثوانٍ في
# كل تشغيل. المسح يجد الكلمة، ثم يقرّر القاموس المناسب.
_DEVTOOLS_TOKEN = re.compile(
    r"(?P<dot>\.)?"
    r"(?P<word>(?!\d)[\w\u064B-\u065F\u0670]+)"
    r"(?P<open>\s*\()?"
)


# أسماء يعرّفها المستخدم في الملف الجاري — لا تُرجمت أبداً (يضبطها inline_replacer)
USER_NAMES = set()


def _devtools_replace(match):
    dot = match.group("dot")
    word = match.group("word")
    open_paren = match.group("open")

    if word in USER_NAMES:
        return match.group(0)

    if dot:
        # بعد نقطة: الطريقة أولاً (لها قوس) ثم الخاصية (بلا قوس)
        if open_paren and word in DEVTOOLS_METHODS:
            return "." + DEVTOOLS_METHODS[word] + open_paren
        if word in DEVTOOLS_PROPS:
            return "." + DEVTOOLS_PROPS[word]
        return match.group(0)

    # بلا نقطة: الثابت العاري، وإلا نداء
    if word in DEVTOOLS_CONSTS:
        return DEVTOOLS_CONSTS[word]
    if word in DEVTOOLS_FUNCS:
        # بلا قوس: صنف أو دالة تُمرَّر كقيمة
        return DEVTOOLS_FUNCS[word] + (open_paren or "")
    return match.group(0)


def DEVTOOLS_SUBSTITUTE(text):
    """يترجم كلمات أدوات المطوّر في نص واحد ويُرجع النص المترجم."""
    if not text:
        return text
    return _DEVTOOLS_TOKEN.sub(_devtools_replace, text)


