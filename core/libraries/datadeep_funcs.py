def _datadeep_replace(match):
    dot = match.group("dot")
    word = match.group("word")
    open_paren = match.group("open")
    if word in USER_NAMES:
        return match.group(0)
    if dot:
        return match.group(0)
    if word in DATD_CONSTS:
        return DATD_CONSTS[word]
    if word in DATD_FUNCS:
        return DATD_FUNCS[word] + (open_paren or "")
    return match.group(0)


