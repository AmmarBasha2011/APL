_POLARS_TOKEN = re.compile(
    r"(?P<dot>\.)?"
    r"(?P<word>(?!\d)[\w\u064B-\u065F\u0670]+)"
    r"(?P<open>\s*\()?"
)

USER_NAMES = set()


def _polars_replace(match):
    dot = match.group("dot")
    word = match.group("word")
    open_paren = match.group("open")
    if word in USER_NAMES:
        return match.group(0)
    if dot:
        return match.group(0)
    if word in POLARS_CONSTS:
        return POLARS_CONSTS[word]
    if word in POLARS_FUNCS:
        return POLARS_FUNCS[word] + (open_paren or "")
    return match.group(0)


def POLARS_SUBSTITUTE(text):
    """يترجم كلمات المكتبة في نص واحد ويُرجع المترجم."""
    if not text:
        return text
    return _POLARS_TOKEN.sub(_polars_replace, text)
