"""Which published library provides a word.

The language ships no vocabulary of its own, so a program that uses a library
word without the library installed fails as an unknown name. This module reads
data/library_words.json (generated by tools/build_library_words.py) so the
error can name the library and the command that installs it.

It is only a map of words to libraries: nothing here adds vocabulary to the
language, and a word still only exists once its library is installed.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path


def data_path() -> Path:
    return Path(__file__).resolve().parent.parent / 'data' / 'library_words.json'


@lru_cache(maxsize=1)
def table() -> dict:
    """Word → library name. Empty when the data file is missing or broken."""
    try:
        data = json.loads(data_path().read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def library_for(word: str) -> str | None:
    """The published library that defines this word, or None."""
    if not word:
        return None
    found = table().get(word.strip())
    return found if isinstance(found, str) and found else None


def hint(word: str) -> str:
    """One Arabic line naming the library that provides the word, or ''."""
    library = library_for(word)
    if not library:
        return ''
    return (f'الكلمة "{word}" من مكتبة apl-{library}. '
            f'سطّبها بـ: عمار مكتبة تحميل {library}')
