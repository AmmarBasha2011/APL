#!/usr/bin/env python3
"""Turn one APL program into a standalone executable.

    عمار بناء برنامج.apl            → dist/برنامج (or برنامج.exe on Windows)
    عمار بناء برنامج.apl --اسم أداة

PyInstaller does the packing; APL itself still needs nothing but the standard
library to run. The program's source is embedded in the executable, so the
result runs on a machine with no APL, no Python and no project folder.

Two kinds of import have to be declared by hand, because the engine reaches
them without a static `import` statement:

* the modules the runtime prologue imports from inside a string (_RUNTIME), and
* the package itself, which is shipped as data and imported at run time.

This module is also usable directly:

    python tools/build_program.py program.apl [--name name] [--dry-run]
"""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

#: Imported by the _RUNTIME prologue in core/runner/main.py (a string, so
#: PyInstaller cannot see these imports).
RUNTIME_MODULES = ['sys', 'builtins', 'pathlib', 'zoneinfo', 'decimal',
                   'fractions', 'string', 'enum', 'secrets', 'getpass',
                   'operator', 'pprint', 'datetime', 'time', 'os', 'shutil',
                   'json', 're', 'itertools', 'collections', 'math', 'random']

ENTRY_TEMPLATE = '''\
# Generated by `عمار بناء`: one APL program, packed into one executable.
import sys

SOURCE = {source!r}
FILENAME = {filename!r}


def main():
    from core.runner.execution import Compilation, execute
    namespace = {{"__name__": "__main__", "__file__": FILENAME}}
    execute(Compilation(SOURCE, FILENAME), namespace)
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def pyinstaller_available() -> bool:
    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        return False
    return True


def command(entry: Path, name: str, work: Path, dist: Path) -> list[str]:
    """The PyInstaller command line for one program."""
    core = ROOT / 'core'
    args = [sys.executable, '-m', 'PyInstaller', '--onefile', '--noconfirm',
            '--clean', '--name', name,
            '--distpath', str(dist), '--workpath', str(work / 'build'),
            '--specpath', str(work),
            '--add-data', f'{core}{os.pathsep}core']
    for module in RUNTIME_MODULES:
        args += ['--hidden-import', module]
    args.append(str(entry))
    return args


def build(program: Path, name: str | None = None, dry_run: bool = False,
          quiet: bool = False) -> dict:
    """Build one program; returns what happened, never raises for a bad build."""
    program = Path(program)
    if not program.is_file():
        return {'ok': False, 'error': f'مفيش ملف اسمه {program}'}
    source = program.read_text(encoding='utf-8')
    # Compile first: an executable that cannot compile is not worth packing,
    # and this is the same check `عمار فحص` makes.
    from core.runner.execution import Compilation
    try:
        Compilation(source, str(program))
    except Exception as error:  # noqa: BLE001 - reported, not raised
        return {'ok': False, 'error': f'البرنامج فيه خطأ ومش هيتحول: {error}'}

    target = (name or program.stem).strip() or program.stem
    work = Path(tempfile.mkdtemp(prefix='apl-build-'))
    entry = work / 'apl_program_entry.py'
    entry.write_text(ENTRY_TEMPLATE.format(source=source, filename=program.name),
                     encoding='utf-8')
    dist = ROOT / 'dist'
    dist.mkdir(exist_ok=True)
    args = command(entry, target, work, dist)

    if dry_run:
        return {'ok': True, 'dry_run': True, 'command': args,
                'entry': str(entry), 'target': str(dist / target)}

    if not pyinstaller_available():
        return {'ok': False, 'needs': 'pyinstaller',
                'error': 'بناء ملف تنفيذي محتاج PyInstaller، وده مش متسطّب.'}

    result = subprocess.run(args, capture_output=True, text=True,
                            encoding='utf-8', errors='replace',
                            cwd=str(ROOT))
    if result.returncode != 0:
        tail = (result.stderr or result.stdout or '').strip().splitlines()[-6:]
        return {'ok': False, 'error': 'فشل البناء:\n' + '\n'.join(tail)}
    executable = dist / (target + ('.exe' if os.name == 'nt' else ''))
    if not executable.is_file():
        return {'ok': False, 'error': f'البناء خلص بس مفيش ملف في {executable}'}
    return {'ok': True, 'path': str(executable),
            'size': executable.stat().st_size}


def main(argv: list[str]) -> int:
    dry_run = '--dry-run' in argv
    name = None
    files: list[str] = []
    index = 0
    while index < len(argv):
        item = argv[index]
        if item == '--name' and index + 1 < len(argv):
            name = argv[index + 1]
            index += 2
            continue
        if not item.startswith('--'):
            files.append(item)
        index += 1
    if not files:
        print('حدد ملف .apl. مثال: عمار بناء برنامج.apl')
        return 1
    outcome = build(Path(files[0]), name=name, dry_run=dry_run)
    if not outcome['ok']:
        print(outcome['error'], file=sys.stderr)
        return 1
    if dry_run:
        print(' '.join(outcome['command']))
        return 0
    print(f"تم: {outcome['path']} ({outcome['size'] // 1024} كيلوبايت)")
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
